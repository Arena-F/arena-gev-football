// Player animation state machine for the 3D replay.
//
// DOM-free and deterministic: locomotion comes from measured speed, while
// one-shot actions are derived from the clip's event time. Asking for the same
// absolute time twice always answers the same action, which is what makes
// scrubbing, pausing and replaying safe. Nothing here mutates engine state.
//
// Event ids follow the Opta F24 mapping used by the engine:
//   1/2 pass, 5 out, 6 corner, 7 tackle, 8 interception, 10 save,
//   12 clearance, 13 miss, 14 post, 15 attempt saved, 16 goal, 17 card,
//   41 punch, 44 aerial, 49 recovery, 52 keeper pick-up, 61 ball touch,
//   74 blocked pass.
//
// Clip timings are generated by tools/bake-mixamo and describe where the key
// contact happens inside each mocap clip. A kick starts 0.31 s before the shot
// event; a header starts 0.48 s before contact so the jump apex lands on the
// event; a tackle starts 0.55 s early and rolls through the recovery.

import { sampleClipInto, STRIDE } from './clipStore.js';
import { MOCAP_TIMING, MOCAP_VARIANTS } from './mixamoTiming.js';

export const LOCOMOTION_NAMES = ['idle', 'walk', 'jog', 'run', 'sprint'];

// Procedural fallback clips that have no mocap source (celebrations).
const FALLBACK_ACTION_DURATION = {
  celebrate_a: 1.2,
  celebrate_b: 1.6,
  celebrate_c: 1.4,
};

export const ACTION_DURATION = (() => {
  const out = { ...FALLBACK_ACTION_DURATION };
  for (const [name, timing] of Object.entries(MOCAP_TIMING)) {
    if (!timing.loop && Number.isFinite(timing.duration)) out[name] = timing.duration;
  }
  return out;
})();

// Locomotion thresholds match the baked gait speeds: walk 1.7, jog 2.6,
// run 4.0, sprint 5.8 m/s. Hysteresis prevents chatter at the boundaries.
const UP = [0.6, 2.0, 3.8, 6.0];
const DOWN = [0.35, 1.6, 3.2, 5.2];

/**
 * Speed -> locomotion level with hysteresis, so a player hovering on a
 * threshold does not strobe between gaits. 0 idle, 1 walk, 2 jog, 3 run,
 * 4 sprint.
 */
export function locomotionLevel(speed, prevLevel = 0) {
  if (!Number.isFinite(speed) || speed <= 0) return 0;
  let level = Math.max(0, Math.min(4, Math.round(prevLevel) || 0));
  while (level < 4 && speed >= UP[level]) level++;
  while (level > 0 && speed < DOWN[level - 1]) level--;
  return level;
}

export function locomotionName(level, isGK = false) {
  if (isGK && level <= 1) return 'gk_idle';
  return LOCOMOTION_NAMES[Math.max(0, Math.min(4, level))] || 'idle';
}

/** Stable per-slot pick from the three celebrations. */
export function celebrationName(hash01) {
  const h = Number.isFinite(hash01) ? hash01 : 0.5;
  if (h < 0.34) return 'celebrate_a';
  if (h < 0.67) return 'celebrate_b';
  if (h < 0.93) return 'celebrate_c';
  return 'stall';
}

/**
 * Deterministic variant pick inside a MOCAP_VARIANTS group (or any name list).
 * Entry [0] is the base clip and owns hash < 0.62, so default and legacy
 * hashes keep the long-tuned base motion; other hashes spread over the
 * same-name variants. The same slot always answers the same variant, so there
 * is no strobing and no cross-group misuse (a header variant never serves a
 * pass). Missing clips fall back to entry [0].
 */
export function pickVariant(variants, hash01) {
  if (!variants || !variants.length) return null;
  if (variants.length === 1) return variants[0];
  const h = Number.isFinite(hash01) ? hash01 : 0.5;
  if (h < 0.62) return variants[0];
  const rest = variants.slice(1);
  const idx = Math.min(rest.length - 1, Math.floor(((h - 0.62) / 0.38) * rest.length));
  return rest[idx];
}

/** Variant pick from a named MOCAP_VARIANTS group, falling back to `base`. */
export function variantFor(group, base, hash01) {
  const list = (MOCAP_VARIANTS && MOCAP_VARIANTS[group]) || [base];
  const name = pickVariant(list, hash01);
  if (name && MOCAP_TIMING[name]) return name;
  return base;
}

function finite(v, fallback) {
  return Number.isFinite(v) ? v : fallback;
}

function isPassType(type) {
  return type === 1 || type === 2 || type === 74;
}

function isShotType(type) {
  return type === 13 || type === 14 || type === 15 || type === 16;
}

function isFoulType(type) {
  return type === 4 || type === 7;
}

function passReceiver(clip, ctx, buf) {
  const { eventT, nearestSlot, eventTeam, playerCount, positions } = ctx;
  const frames = clip.frames;
  const lastT = Number.isFinite(clip.endT) ? clip.endT : frames[frames.length - 1].t;
  const until = Math.min(lastT, eventT + 3.0);
  let best = { slot: -1, t: null, dist: Infinity };

  // Walk the future ball path and find the same-team teammate it arrives
  // closest to. The passer is excluded so a short pass does not nominate the
  // player who just released it.
  for (let t = eventT + 0.2; t <= until + 1e-6; t += 0.1) {
    const data = sampleClipInto(clip, t, buf);
    if (!data) break;
    const ballO = playerCount * STRIDE;
    const bx = data[ballO];
    const by = data[ballO + 1];
    for (let slot = 0; slot < playerCount; slot++) {
      if (slot === nearestSlot) continue;
      const p = positions[slot];
      if (!p || p.team !== eventTeam) continue;
      const d = Math.hypot(p.x - bx, p.y - by);
      if (d < best.dist) best = { slot, t, dist: d };
    }
  }

  if (best.slot >= 0 && best.dist < 12) {
    ctx.receiverSlot = best.slot;
    ctx.receiveT = best.t;
    ctx.receiveDist = best.dist;
  }
  return ctx;
}

/**
 * Read the clip once at event time and cache who was closest to the ball, the
 * defending keeper, the ball's lateral side and (for passes) the likely
 * receiver. Rebuilt per frame from the sampled data, so a seek rebuilds it
 * correctly.
 */
export function buildEventContext(clip, roles = []) {
  const frames = clip && clip.frames;
  const event = clip && clip.event;
  if (!frames || !frames.length || !event || !Number.isFinite(event.t)) return null;
  const first = frames[0];
  const count = first.count;
  const buf = new Float32Array(count * STRIDE);
  const data = sampleClipInto(clip, event.t, buf);
  if (!data) return null;

  const playerCount = Math.max(0, count - 1);
  const ballX = data[playerCount * STRIDE];
  const ballY = data[playerCount * STRIDE + 1];
  const ballZ = data[playerCount * STRIDE + 2];
  const originX = finite(event.x, ballX);
  const originY = finite(event.y, ballY);
  const eventTeam = (event.team === 0 || event.team === 1) ? event.team : null;

  let nearestSlot = -1;
  let nearestDist = Infinity;
  let nearestOppSlot = -1;
  let nearestOppDist = Infinity;
  const gkSlots = [];
  const gkByTeam = [null, null];
  const positions = new Array(playerCount);

  for (let slot = 0; slot < playerCount; slot++) {
    const o = slot * STRIDE;
    const x = data[o];
    const y = data[o + 1];
    const team = data[o + 4];
    positions[slot] = { x, y, team };
    if (roles[slot] === 1) {
      gkSlots.push(slot);
      if (team === 0 || team === 1) gkByTeam[team] = slot;
    }
    const d = Math.hypot(x - originX, y - originY);
    if (eventTeam == null || team === eventTeam) {
      if (d < nearestDist) {
        nearestDist = d;
        nearestSlot = slot;
      }
    }
    if (eventTeam != null && team !== eventTeam) {
      if (d < nearestOppDist) {
        nearestOppDist = d;
        nearestOppSlot = slot;
      }
    }
  }

  const ctx = {
    event,
    eventT: event.t,
    eventType: event.type,
    eventTeam,
    ballX,
    ballY,
    ballZ,
    originX,
    originY,
    nearestSlot,
    nearestOppSlot,
    gkSlots,
    gkByTeam,
    playerCount,
    positions,
    receiverSlot: -1,
    receiveT: null,
    receiveDist: Infinity,
  };

  if (isPassType(event.type) && eventTeam != null && nearestSlot >= 0) {
    passReceiver(clip, ctx, buf);
  }
  return ctx;
}

function windowAction(name, start, until, loop = false) {
  return { name, start, until: Math.max(start + 0.05, until), loop };
}

/** Start a clip so its contact point lands on `eventT`. */
function contactAction(name, eventT, { lead, tail, loop = false } = {}) {
  const timing = MOCAP_TIMING[name] || {};
  const startLead = Number.isFinite(lead) ? lead : (Number.isFinite(timing.lead) ? timing.lead : 0.3);
  const duration = Number.isFinite(timing.duration) ? timing.duration : 0.9;
  const start = eventT - startLead;
  const finish = Number.isFinite(tail) ? eventT + tail : start + duration;
  return windowAction(name, start, finish, loop);
}

function diveFor(ctx, gkSlot) {
  if (gkSlot == null || gkSlot < 0) return null;
  const gk = ctx.positions[gkSlot];
  if (!gk) return null;
  return ctx.ballY - gk.y < 0 ? 'gk_dive_l' : 'gk_dive_r';
}

function keeperAction(ctx, gkSlot, eventT, kind, hash01 = 0.5) {
  if (gkSlot == null || gkSlot < 0) return null;
  const gk = ctx.positions[gkSlot];
  const lateral = gk ? Math.abs(ctx.ballY - gk.y) : 0;

  if (kind === 'save') {
    // The save event happens when the keeper has the ball. A central save is a
    // catch/body block; a wide one is the tail of a dive.
    if (lateral > 0.9) return contactAction(diveFor(ctx, gkSlot), eventT, { lead: 0.85 });
    return contactAction(variantFor('gk_catch', 'gk_catch', hash01), eventT);
  }
  if (kind === 'pickup') return contactAction('gk_scoop', eventT);
  if (kind === 'punch') return contactAction(variantFor('gk_block', 'gk_block', hash01), eventT, { lead: 0.35 });

  // A shot: the keeper starts moving as the ball is struck. The dive's catch
  // lands later, so use a short lead rather than the clip's contact point.
  if (lateral > 0.55) return contactAction(diveFor(ctx, gkSlot), eventT, { lead: 0.3 });
  return contactAction(variantFor('gk_block', 'gk_block', hash01), eventT, { lead: 0.3 });
}

/**
 * Which action, if any, the player in `slot` should be playing at `tAbs`.
 * Returns null for locomotion. Windows overlap deliberately: a kick rolls into
 * the celebration, a foul rolls from the fall into the get-up.
 */
export function actionForSlot(slot, tAbs, ctx, opts) {
  const action = actionForSlotRaw(slot, tAbs, ctx, opts);
  if (!action) return null;
  // Outside its own window the action is not "the action for this slot"; the
  // player would fade it to zero anyway, but returning it here would hide a
  // later action such as the celebration after the kick.
  if (tAbs < action.start - 1e-6 || tAbs > action.until + 1e-6) return null;
  return action;
}

function actionForSlotRaw(slot, tAbs, ctx, { isGK = false, team = 0, hash01 = 0.5 } = {}) {
  if (!ctx || !Number.isFinite(tAbs) || slot < 0) return null;
  const { eventT, eventType, eventTeam } = ctx;
  const dt = tAbs - eventT;
  const sameTeam = eventTeam != null && team === eventTeam;
  const otherTeam = eventTeam != null && team !== eventTeam;
  if (eventTeam == null) return null;

  // Goal: only type 16. Type 17 is a card and must not trigger a celebration.
  if (eventType === 16 && sameTeam) {
    if (dt >= 0.55 && dt <= 5.4) {
      const name = celebrationName(hash01);
      return windowAction(name, eventT + 0.55, eventT + 5.2, true);
    }
  }

  // Defending keeper on a shot or a goal.
  if ((isShotType(eventType) || eventType === 10) && isGK) {
    const defending = ctx.gkByTeam[eventTeam === 0 ? 1 : 0];
    const saving = ctx.gkByTeam[eventTeam];
    if (eventType === 10 && slot === saving) {
      return keeperAction(ctx, slot, eventT, 'save', hash01);
    }
    if (eventType === 15 && slot === defending) {
      return keeperAction(ctx, slot, eventT, 'save', hash01);
    }
    if (eventType !== 10 && eventType !== 15 && slot === defending) {
      // A goal beats the keeper: most keepers dive, some miss outright.
      if (eventType === 16 && hash01 >= 0.62) {
        return contactAction('gk_miss', eventT, { lead: 0.3, tail: 1.7 });
      }
      return keeperAction(ctx, slot, eventT, 'shot', hash01);
    }
  }

  // A saved shot still needs the shooter's strike, just before the save event.
  if (eventType === 10 && otherTeam && slot === ctx.nearestOppSlot) {
    return contactAction('kick', eventT, { lead: 0.65 });
  }

  // Attacking keeper distribution.
  if (isGK && sameTeam && eventType === 52 && slot === ctx.gkByTeam[eventTeam]) {
    return keeperAction(ctx, slot, eventT, 'pickup');
  }
  if (isGK && sameTeam && eventType === 41 && slot === ctx.gkByTeam[eventTeam]) {
    return keeperAction(ctx, slot, eventT, 'punch');
  }
  if (isGK && sameTeam && eventType === 59 && slot === ctx.gkByTeam[eventTeam]) {
    return contactAction('kick', eventT, { lead: 0.31 });
  }

  // Foul/tackle pair: the event team made the tackle, the opponent goes down.
  if (isFoulType(eventType)) {
    if (sameTeam && slot === ctx.nearestSlot) {
      return contactAction(variantFor('tackle', 'tackle', hash01), eventT, { lead: 0.65 });
    }
    if (otherTeam && slot === ctx.nearestOppSlot) {
      if (dt >= 2.4 && dt <= 4.2) {
        return windowAction('getup', eventT + 2.4, eventT + 2.4 + (ACTION_DURATION.getup || 1.67));
      }
      if (dt >= 1.0 && dt <= 2.6) {
        return windowAction('fallen_idle', eventT + 1.0, eventT + 2.6, true);
      }
      if (dt >= -0.05 && dt <= 1.35) {
        return contactAction(variantFor('fall', 'fall', hash01), eventT, { lead: 0.0, tail: 1.35 });
      }
    }
  }

  // Passer and receiver. The receiver is found from the future ball path.
  // High balls are chipped rather than side-footed.
  if (isPassType(eventType)) {
    if (sameTeam && slot === ctx.nearestSlot && slot !== ctx.receiverSlot) {
      const high = Number.isFinite(ctx.ballZ) && ctx.ballZ > 1.0;
      const name = high ? 'pass_chip' : variantFor('pass', 'pass', hash01);
      return contactAction(name, eventT);
    }
    if (sameTeam && slot === ctx.receiverSlot && Number.isFinite(ctx.receiveT)) {
      if (tAbs >= ctx.receiveT - 0.5 && tAbs <= ctx.receiveT + 0.85) {
        if (isGK) return contactAction('gk_catch', ctx.receiveT);
        return contactAction(variantFor('receive', 'receive', hash01), ctx.receiveT);
      }
    }
    if (otherTeam && slot === ctx.nearestOppSlot && eventType === 74) {
      return contactAction('kick', eventT, { lead: 0.31 });
    }
  }

  // Aerial duel: both closest players jump for the header.
  if (eventType === 44) {
    if (slot === ctx.nearestSlot || slot === ctx.nearestOppSlot) {
      return contactAction(variantFor('header', 'header', hash01), eventT);
    }
  }

  // Take-on / failed challenge: a control turn and a lunging miss.
  if (eventType === 3 && sameTeam && slot === ctx.nearestSlot) {
    return contactAction(variantFor('receive', 'receive', hash01), eventT, { lead: 0.2, tail: 0.9 });
  }
  if (eventType === 45 && sameTeam && slot === ctx.nearestSlot) {
    return contactAction(variantFor('tackle', 'tackle', hash01), eventT, { lead: 0.4 });
  }

  // Shots: the nearest attacker strikes; the keeper path above handles the
  // save. For a saved attempt the strike happens before the save event.
  if (isShotType(eventType) && sameTeam && slot === ctx.nearestSlot) {
    const high = Number.isFinite(ctx.ballZ) && ctx.ballZ > 1.0;
    if (high) {
      return eventType === 15
        ? contactAction('volley', eventT, { lead: 0.65 })
        : contactAction('volley', eventT);
    }
    if (eventType === 15) return contactAction('kick', eventT, { lead: 0.65 });
    return contactAction('kick', eventT);
  }

  // Dead-ball and loose-ball actions.
  if (sameTeam && slot === ctx.nearestSlot) {
    if (eventType === 5) {
      const wide = Math.abs(ctx.originY) > 26 || Math.abs(ctx.ballY) > 26;
      if (wide) return contactAction('throw_in', eventT);
      if (isGK) {
        // Keeper restarts: place the ball, then launch it. The place window
        // ends as the distribution window starts.
        if (tAbs <= eventT + 0.6) {
          return windowAction('gk_place', eventT - 1.6, eventT + 0.6);
        }
        const dist = pickVariant(['kick', 'gk_dist_pass', 'gk_dist_drop'], hash01);
        return contactAction(dist, eventT, { lead: -0.5 });
      }
      // A goal kick/restart happens after the ball goes out.
      return contactAction('kick', eventT, { lead: -0.5 });
    }
    if (eventType === 6) {
      // Corner award: the taker walks over and crosses after the award.
      return contactAction(variantFor('pass', 'pass', hash01), eventT, { lead: -0.8 });
    }
    if (eventType === 8 || eventType === 49 || eventType === 61) {
      if (isGK) {
        return contactAction(
          pickVariant(['gk_catch', 'gk_dist_throw'], hash01), eventT, { lead: 0.2, tail: 0.8 });
      }
      return contactAction(variantFor('receive', 'receive', hash01), eventT, { lead: 0.2, tail: 0.8 });
    }
    if (eventType === 12) return contactAction('kick', eventT);
    if (eventType === 44) return contactAction(variantFor('header', 'header', hash01), eventT);
  }

  return null;
}

/** Fade in/out envelope for an action window. 0 outside, 1 held inside. */
export function actionWeight(action, tAbs, fadeIn = 0.12, fadeOut = 0.18) {
  if (!action) return 0;
  const local = tAbs - action.start;
  const remain = action.until - tAbs;
  if (local < -1e-6 || remain < -1e-6) return 0;
  return Math.max(0, Math.min(1, local / Math.max(1e-3, fadeIn), remain / Math.max(1e-3, fadeOut)));
}
